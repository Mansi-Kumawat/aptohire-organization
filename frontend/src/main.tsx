import React from 'react';
import ReactDOM from 'react-dom/client';
import {BrowserRouter} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {HelmetProvider} from 'react-helmet-async';
import App from './app/App';
import './styles/tokens.css';
import './styles/global.css';
const client=new QueryClient({defaultOptions:{queries:{retry:1,refetchOnWindowFocus:false}}});
ReactDOM.createRoot(document.getElementById('root')!).render(<React.StrictMode><HelmetProvider><QueryClientProvider client={client}><BrowserRouter><App/></BrowserRouter></QueryClientProvider></HelmetProvider></React.StrictMode>);